/**
 * What the numbers in this database MEAN.
 *
 * `PRAGMA table_info` tells a model that `transactions.amount` is an INTEGER. It does not tell it
 * that the integer is cents, that a negative one means money left the account, that a positive one
 * inside an expense category is a refund rather than income, or that summing the column without
 * `excludedFromTotalsSql` counts the owner's own transfers as spending. Every one of those has
 * already produced a wrong number on a screen in this app; the advisor reported $1,695.00 of
 * spending where Reports reported $75.00 on the same data, and the difference was entirely which
 * rows each side thought counted.
 *
 * So this file is a dictionary, not a dump. It is versioned in the repo and read by
 * `describe_schema`, which composes it with the live column list so that nothing is described that
 * does not exist.
 *
 * TWO RULES HOLD IT HONEST.
 *
 * 1. The spend/income predicates are GENERATED by calling the real functions in
 *    `transactionFilters.ts`, never transcribed. A transcription drifts silently the first time the
 *    predicate changes, and the model would go on pasting the old text.
 * 2. Nothing here states a live figure. "2,412 of 2,579 rows have a NULL `category_source`" is true
 *    today and false after the next sync, so the doc states what NULL MEANS and the observed
 *    distribution is counted at call time from the database in front of it.
 */

/** Bump when a meaning changes, so a cached prompt prefix can be told the dictionary moved. */
export const SCHEMA_DOC_VERSION = 1;

export interface ColumnMeaning {
  /** What the stored number or string IS, in units. Short enough to read at a glance. */
  unit: string;
  /** Sign convention, NULL meaning, and anything that has already been read wrongly. */
  note?: string;
}

export interface TableMeaning {
  purpose: string;
  columns: Record<string, ColumnMeaning>;
}

