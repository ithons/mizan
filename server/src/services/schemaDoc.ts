/**
 * Does the Reports page count this row?
 *
 * Answered by evaluating the SAME predicate strings this file publishes, against the row itself,
 * rather than by re-deciding it in TypeScript. `get_transaction_full` used to answer it with
 * `excludedFromTotalsSql`'s two flags alone, which omits both `pending = 0` and the recursive
 * cat_xfer / cat_inv / cat_crypto scope that reporting.ts applies on top of them.
 *
 * MEASURED, on a copy of the owner's database, over the 120 transactions dated 2026-07-01 to
 * 2026-07-31: the old two-flag test called 112 of them counted, this function calls 102, and the
 * ten it stops claiming are eight $100 Fidelity contributions in `cat_inv_transfer`, a $780 cash
 * deposit in `cat_xfer_in` and a $5.00 Venmo transfer in `cat_xfer_out`, every one of them sitting
 * at `transfer_status = 'none'`, which is the ordinary state before the pairing pass runs. Summing
 * the rows this function DOES count reproduces getSpendingReport's 78222 and getCashflowReport's
 * income of 217122 for that month exactly. A boolean handed to the model as fact has to be the
 * boolean the page uses.
 *
 * Null when no such row exists, so the caller says so rather than inventing an answer.
 */
export function transactionReportInclusion(
  db: Database.Database,
  transactionId: string
): TransactionReportInclusion | null {
  const row = db
    .prepare(
      `${REPORT_SCOPE_CTE}
       SELECT
         CASE WHEN ${excludedFromTotalsSql('t')} THEN 1 ELSE 0 END AS kept_by_resolution,
         CASE WHEN ${REPORT_SCOPE_CONDITION} THEN 1 ELSE 0 END AS in_report_scope,
         COALESCE(t.pending, 0) AS pending,
         CASE WHEN ${expenseSideSql('t', 'c')} THEN 1 ELSE 0 END AS expense_side,
         CASE WHEN ${incomeSideSql('t', 'c')} THEN 1 ELSE 0 END AS income_side,
         t.transfer_status, t.duplicate_status, t.category_id, t.amount,
         c.is_investment
       FROM transactions t
       LEFT JOIN categories c ON c.id = t.category_id
       WHERE t.id = ?`
    )
    .get(transactionId) as InclusionRow | undefined;
  if (!row) return null;

  const side = row.expense_side === 1 ? 'expense' : row.income_side === 1 ? 'income' : null;
  const counts =
    row.kept_by_resolution === 1 && row.in_report_scope === 1 && row.pending === 0 && side !== null;

  const excluded: string[] = [];
  if (row.pending === 1) {
    excluded.push('pending = 1: every report applies t.pending = 0, so a pending row counts nowhere until it posts.');
  }
  if (row.transfer_status === 'candidate' || row.transfer_status === 'confirmed') {
    excluded.push(
      `transfer_status = '${row.transfer_status}': excluded_from_totals drops both legs of a transfer, candidate as well as confirmed.`
    );
  }
  if (row.duplicate_status === 'confirmed') {
    excluded.push("duplicate_status = 'confirmed': excluded_from_totals drops a copy the owner resolved.");
  }
  if (row.in_report_scope === 0) {
    excluded.push(
      `category_id = '${String(row.category_id)}' sits inside the transfer, investment or crypto category tree (cat_xfer, cat_inv, cat_crypto and their children), which the reports drop wholesale, children included.`
    );
  }
  if (side === null) {
    excluded.push(
      row.is_investment === 1
        ? `category_id = '${String(row.category_id)}' is classed as an investment flow (categories.is_investment = 1), which expense_side excludes so moving money into a brokerage does not read as spending it.`
        : `neither income_side nor expense_side claims this row (category_id = ${String(row.category_id)}, amount = ${row.amount} cents), so it lands in no report total.`
    );
  }
  // The list is built from the same row the boolean is, but it is assembled by hand, so a silent
  // disagreement between "does not count" and "here is why" is possible. Say so rather than
  // returning an empty explanation for an excluded row.
  if (!counts && excluded.length === 0) {
    excluded.push('excluded by the report predicates, with no more specific reason available. See predicates.example.');
  }

  return { counts, side, excluded_because: excluded };
}

export interface SchemaDocColumn {
  name: string;
  type: string;
  unit?: string;
  note?: string;
}

/**
 * A table in the doc, at one of two levels of detail.
 *
 * The two levels are DIFFERENT SHAPES rather than the same shape with fields missing. A
 * `names_only` table is one whose meanings were not asked for, and if it carried an empty-noted
 * `columns` array it would be indistinguishable from a table nothing is documented about, which is
 * the same class of wrong reading this whole file exists to stop.
 */
export type SchemaDocTable =
  | { table: string; purpose: string | null; detail: 'full'; columns: SchemaDocColumn[] }
  | { table: string; purpose: string | null; detail: 'names_only'; column_names: string };

export interface SchemaDocEnum extends EnumMeaning {
  /** Value -> row count, counted from this database now. Absent when the table has no rows. */
  observed: Record<string, number>;
  /** Values present in the data with no documented meaning. Normally empty. */
  undocumented_values: string[];
}

export interface SchemaDoc {
  version: number;
  tables: SchemaDocTable[];
  /** Which tables came back expanded, and how to ask for the rest. */
  detail: {
    expanded: string[];
    note: string;
  };
  money: {
    rule: string;
    real_dollar_exceptions: string[];
    not_money: string[];
  };
  sign_conventions: string[];
  predicates: {
    usage: string;
    excluded_from_totals: string;
    income_side: string;
    expense_side: string;
    spend_amount: string;
    report_scope_cte: string;
    report_scope_condition: string;
    example: string;
    /** What date range `example` carries, so a pasted month is never assumed to be the one wanted. */
    example_range: string;
  };
  enums: Record<string, SchemaDocEnum>;
  time: {
    today_local: string;
    local_dates: string;
    utc_timestamps: string;
    warning: string;
  };
  reconstructions: string[];
}

const NULL_KEY = 'NULL';

/**
 * Live value distribution for one enum column.
 *
 * Counted rather than asserted: the point of the `category_source` entry is that most rows are
 * NULL, and a hardcoded number would be wrong by the next sync. Any value present in the data with
 * no documented meaning is surfaced instead of being quietly rendered as a bare string.
 */
function observeEnum(db: Database.Database, meaning: EnumMeaning): {
  observed: Record<string, number>;
  undocumented: string[];
} {
  const rows = db
    .prepare(
      `SELECT COALESCE(CAST("${meaning.column}" AS TEXT), '${NULL_KEY}') AS value, COUNT(*) AS n
       FROM "${meaning.table}" GROUP BY 1 ORDER BY 2 DESC`
    )
    .all() as Array<{ value: string; n: number }>;

  const observed: Record<string, number> = {};
  const undocumented: string[] = [];
  for (const row of rows) {
    observed[row.value] = row.n;
    if (row.value !== NULL_KEY && !(row.value in meaning.values)) undocumented.push(row.value);
  }
  return { observed, undocumented };
}

export interface ProvenanceSummary {
  total_transactions: number;
  categorized: number;
  uncategorized: number;
  by_source: Array<{ source: string; meaning: string; transactions: number }>;
  /** Rows an AI action still owns, so an undo can still put them back. */
  ai_rows_with_a_live_action: number;
  /** Rows the owner chose by hand, under either marker. These are never overwritten. */
  owner_chosen: number;
}

/**
 * Who chose the category on each row.
 *
 * The single most misread column in this schema. `category_source` is NULL on most of the ledger
 * because provenance only arrived in migration 041, and a model that reads NULL as zero concludes
 * the owner has categorized nothing, or that the machine did all of it. Both are wrong, and both
 * lead somewhere destructive: the second one invites a bulk re-categorization over the owner's own
 * decisions.
 *
 * Every figure here is counted from the database, never asserted.
 */
export function getCategoryProvenance(db: Database.Database): ProvenanceSummary {
  const totals = db
    .prepare(
      `SELECT COUNT(*) AS total,
              SUM(CASE WHEN category_id IS NOT NULL THEN 1 ELSE 0 END) AS categorized,
              SUM(CASE WHEN category_source = 'ai' AND category_action_id IS NOT NULL THEN 1 ELSE 0 END) AS ai_live,
              SUM(CASE WHEN manually_categorized = 1 OR category_source = 'human' THEN 1 ELSE 0 END) AS owner_chosen
       FROM transactions`
    )
    .get() as { total: number; categorized: number | null; ai_live: number | null; owner_chosen: number | null };

  const meanings = ENUM_MEANINGS.category_source.values;
  const bySource = (
    db
      .prepare(
        `SELECT COALESCE(category_source, '${NULL_KEY}') AS source, COUNT(*) AS n
         FROM transactions GROUP BY 1 ORDER BY 2 DESC`
      )
      .all() as Array<{ source: string; n: number }>
  ).map((row) => ({
    source: row.source,
    meaning:
      row.source === NULL_KEY
        ? 'Categorized before provenance existed (migration 041). Nothing recorded who chose. NOT zero, and NOT the machine.'
        : meanings[row.source] ?? 'Undocumented value; see services/schemaDoc.ts.',
    transactions: row.n,
  }));

  return {
    total_transactions: totals.total,
    categorized: totals.categorized ?? 0,
    uncategorized: totals.total - (totals.categorized ?? 0),
    by_source: bySource,
    ai_rows_with_a_live_action: totals.ai_live ?? 0,
    owner_chosen: totals.owner_chosen ?? 0,
  };
}

function liveTables(db: Database.Database): string[] {
  return (
    db
      .prepare("SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name")
      .all() as Array<{ name: string }>
  ).map((row) => row.name);
}

function liveColumns(db: Database.Database, table: string): Array<{ name: string; type: string }> {
  return db.prepare(`PRAGMA table_info("${table.replace(/"/g, '""')}")`).all() as Array<{
    name: string;
    type: string;
  }>;
}

/**
 * The tables whose column meanings ship on every call, whatever was asked for.
 *
 * Every spend or income query reads all three, and the readings that have already produced a wrong
 * number on a screen here (cents, the refund sign, the transfer/investment category classes) live
 * on their columns. The other 26 tables are listed with their purpose and their column names, and
 * `describeTables` expands any of them on request.
 *
 * MEASURED, on a copy of the owner's database, as
 * `Buffer.byteLength(JSON.stringify(buildSchemaDoc(db)), 'utf8')`: expanding all 29 tables on every
 * call was 34,398 bytes, roughly 8.6k tokens, landing uncached inside a tool loop that runs up to 8
 * rounds. The core three plus the index is 25,507 bytes, and `describeTables(db, ['holdings'])` is
 * 1,622, so asking for one more table costs a twentieth of what carrying all of them did.
 */
const ALWAYS_DETAILED_TABLES = ['transactions', 'accounts', 'categories'];

function describeOneTable(db: Database.Database, table: string, full: boolean): SchemaDocTable {
  const meaning = TABLE_MEANINGS[table];
  const purpose = meaning?.purpose ?? null;
  const columns = liveColumns(db, table);
  if (!full) {
    return { table, purpose, detail: 'names_only', column_names: columns.map((c) => c.name).join(', ') };
  }
  return {
    table,
    purpose,
    detail: 'full',
    columns: columns.map((column) => {
      const columnMeaning = meaning?.columns[column.name];
      return {
        name: column.name,
        type: column.type || 'ANY',
        ...(columnMeaning ? { unit: columnMeaning.unit, note: columnMeaning.note } : {}),
      };
    }),
  };
}

export interface TableDetail {
  version: number;
  tables: SchemaDocTable[];
  /** Names that are not tables in this database. Reported rather than silently returning nothing. */
  requested_but_unknown: string[];
  note: string;
}

/**
 * Full column meanings for named tables, and nothing else.
 *
 * The expansion has to be CHEAP or it is not worth having: re-sending the predicates, the enum
 * distributions and the whole table index alongside one expanded table would cost more than the
 * fat default it is meant to replace. So this returns the tables asked for and says plainly that
 * the rest of the dictionary was not repeated, rather than leaving the model to assume either way.
 */
export function describeTables(db: Database.Database, requested: string[]): TableDetail {
  const live = new Set(liveTables(db));
  const known = requested.filter((table) => live.has(table));
  return {
    version: SCHEMA_DOC_VERSION,
    tables: known.map((table) => describeOneTable(db, table, true)),
    requested_but_unknown: requested.filter((table) => !live.has(table)),
    note:
      'Column meanings for the tables asked for. The money rules, sign conventions, spend and income predicates, enum meanings and today\'s local date are NOT repeated here: call describe_schema with no arguments to get them, and do that before writing a spend or income query.',
  };
}

/**
 * The dictionary, composed with the schema actually in front of us.
 *
 * Column lists come from the database, so no column is described that does not exist. Meanings come
 * from `TABLE_MEANINGS`, so a meaning for a column that was dropped simply never attaches. The
 * reverse direction (a documented column that vanished) is caught by tests/schemaDoc.test.ts
 * against the migrated schema, which is where a drift like that should be found.
 *
 * Every table is always LISTED with its purpose and its column names; `ALWAYS_DETAILED_TABLES` also
 * carry per-column units and notes, and each table says which it got.
 */
export function buildSchemaDoc(db: Database.Database, now: Date = new Date()): SchemaDoc {
  const live = liveTables(db);
  const expanded = ALWAYS_DETAILED_TABLES.filter((table) => live.includes(table));
  const tables: SchemaDocTable[] = live.map((table) => describeOneTable(db, table, expanded.includes(table)));

  const present = new Set(tables.map((t) => t.table));
  const enums: Record<string, SchemaDocEnum> = {};
  for (const [key, meaning] of Object.entries(ENUM_MEANINGS)) {
    if (!present.has(meaning.table)) continue;
    const { observed, undocumented } = observeEnum(db, meaning);
    enums[key] = { ...meaning, observed, undocumented_values: undocumented };
  }

  return {
    version: SCHEMA_DOC_VERSION,
    tables,
    detail: {
      expanded: [...expanded].sort(),
      note:
        'Every table in this database is listed above with its purpose and its column names. A table marked detail = "names_only" has had its per-column units and notes withheld to keep this payload small; that is NOT a statement that none are documented. Call describe_schema again with tables: ["holdings", "budgets"] to expand any of them, and do that before writing SQL against a table you have only seen the names of.',
    },
    money: {
      rule:
        'Every money TOTAL is an INTEGER number of CENTS. Divide by 100 for dollars, and do the dividing once, at the end, so intermediate sums stay exact.',
      real_dollar_exceptions: [
        'holdings.institution_price and holdings_history.institution_price are REAL DOLLARS PER UNIT, not cents. Crypto spot prices live here. Rounding a $0.003 token to whole cents destroys it, which is why these columns were left REAL. Do not divide them by 100.',
      ],
      not_money: [
        'transactions.quantity is a REAL count of units of transactions.security_id. Not cents, not dollars.',
        'holdings.quantity and holdings_history.quantity are REAL share or coin counts.',
        'accounts.native_balance is a REAL count of native-currency units (coins for a wallet), not a dollar figure.',
        'recurring_patterns.amount_variance is a REAL ratio.',
        'Every *_count, covered_accounts, total_accounts and transactions_* column on sync_runs is a plain count.',
      ],
    },
    sign_conventions: [
      'transactions.amount: negative means money LEFT the account, positive means it ARRIVED.',
      'A liability balance (accounts.is_liability = 1) is stored POSITIVE as the amount OWED and is SUBTRACTED from net worth. It may legitimately be NEGATIVE, which means the card is in credit and the bank owes the owner money, and that RAISES net worth. Never Math.abs it, never clamp it to zero, and read a negative one as "owes you", not "you owe".',
      'A refund is a POSITIVE amount inside an EXPENSE category. It is not income. It nets its own category down, so a category total can legitimately be negative in a month with large returns.',
      'A negative amount inside an INCOME category is a payroll correction, and it nets income down for the same reason.',
      'transactions.quantity is the signed change in units held: positive means units arrived. For a trade that is the OPPOSITE sign to amount, because a buy is money out and units in.',
      'Reconciliation expresses both sides as a movement in NET WORTH, so a liability\'s balance movement is negated before it is compared with the ledger.',
    ],
    predicates: {
      usage:
        'EVERY query that sums transactions as spend or income must apply excluded_from_totals, must decide the side with income_side / expense_side rather than by the sign of the amount, and must carry report_scope_cte plus report_scope_condition so the transfer, investment and crypto category trees stay out. The first four strings are generated from services/transactionFilters.ts, so they are exactly what the Reports page uses. Paste them; do not paraphrase them. Skipping them is how the advisor once reported $1,695.00 of spending against Reports\' $75.00 on the same data. When a figure simply has to match the Reports page, prefer the spending_by_category and monthly_cashflow tools over writing it yourself.',
      excluded_from_totals: excludedFromTotalsSql('t'),
      income_side: incomeSideSql('t', 'c'),
      expense_side: expenseSideSql('t', 'c'),
      spend_amount: spendAmountSql('t'),
      report_scope_cte: REPORT_SCOPE_CTE,
      report_scope_condition: REPORT_SCOPE_CONDITION,
      // Derived from the same `now` as time.today_local. Hardcoded literals made the example a
      // stale month sitting next to a correct date the moment the calendar turned over, on a doc
      // whose own text calls it ready to paste.
      example: spendExampleSql(
        `'${format(startOfMonth(now), 'yyyy-MM-dd')}'`,
        `'${format(endOfMonth(now), 'yyyy-MM-dd')}'`
      ),
      example_range: `The CURRENT local month, ${format(startOfMonth(now), 'yyyy-MM-dd')} to ${format(endOfMonth(now), 'yyyy-MM-dd')}. Swap both literals for the range you actually want.`,
    },
    enums,
    time: {
      today_local: format(now, 'yyyy-MM-dd'),
      local_dates:
        'transactions.date, net_worth_snapshots.date, holdings_history.date, goals.target_date and every other bare date column is a LOCAL calendar date, TEXT yyyy-MM-dd.',
      utc_timestamps: 'created_at, updated_at, started_at, completed_at, retired_at and calculated_at are ISO 8601 UTC timestamps.',
      warning:
        "SQLite's date('now') is UTC and DISAGREES with this app's local month boundaries, so it can put a transaction in the wrong month. Use the today_local literal above, and write date ranges as literals, instead of calling date('now').",
    },
    reconstructions: [
      'net_worth_snapshots with is_estimated = 1 are RECONSTRUCTED by replaying transactions backwards off current balances. They are not measurements and cannot be evidence about the ledger they came from. Reconciliation ignores them for exactly that reason. Say "estimated" when you quote one.',
      'The per-account daily balance series (services/balanceHistory.ts, GET /api/accounts/:id/balance-history) is DERIVED from the ledger the same way, except on the days that carry a recorded balance sheet. Where the derived line and a recorded balance disagree, the disagreement is the finding; neither side is automatically right.',
      'recurring_patterns.average_amount on a variable series is a median of past occurrences, and buildRecurringForecast marks those occurrences amount_varies. A forecast is not a fact.',
      'holdings.cost_basis is whatever the provider reported. NULL means unknown, and no cost basis is derived from the ledger in this app because the disposal history was never imported.',
    ],
  };
}
