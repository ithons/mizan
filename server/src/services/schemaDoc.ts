/**
 * The three category trees Reports leaves out of spend and income entirely.
 *
 * `excludedFromTotalsSql` removes rows the OWNER resolved (transfers, confirmed duplicates), and
 * `expenseSideSql` removes investment-classed categories. Neither removes the transfer category
 * tree from a query that reaches it another way, and reporting.ts drops those roots with a
 * recursive CTE on top of both. Leaving it out of the worked example below made that example
 * disagree with the Reports page by $775.00 on the owner's own July, which is precisely the failure
 * this dictionary exists to stop.
 *
 * The root ids are duplicated from reporting.ts because they are private there. That duplication is
 * pinned by tests/schemaDoc.test.ts, which asserts the example returns the same figure as
 * `getSpendingReport` on a fixture carrying a transfer, a refund and an investment flow, so a
 * change to the report's scope fails rather than drifts.
 */
const REPORT_SCOPE_ROOT_IDS = ['cat_xfer', 'cat_inv', 'cat_crypto'];

const REPORT_SCOPE_CTE = [
  'WITH RECURSIVE excluded_report_categories(id) AS (',
  `  SELECT id FROM categories WHERE id IN (${REPORT_SCOPE_ROOT_IDS.map((id) => `'${id}'`).join(', ')})`,
  '  UNION ALL',
  '  SELECT c.id FROM categories c JOIN excluded_report_categories e ON c.parent_id = e.id',
  ')',
].join('\n');

const REPORT_SCOPE_CONDITION =
  '(t.category_id IS NULL OR t.category_id NOT IN (SELECT id FROM excluded_report_categories))';

/** The whole spend query, assembled from the same pieces, ready to paste. */
export function spendExampleSql(startDateLiteral: string, endDateLiteral: string): string {
  return [
    REPORT_SCOPE_CTE,
    `SELECT SUM(${spendAmountSql('t')}) AS spend_cents`,
    'FROM transactions t',
    'LEFT JOIN categories c ON c.id = t.category_id',
    `WHERE ${excludedFromTotalsSql('t')}`,
    `  AND ${REPORT_SCOPE_CONDITION}`,
    `  AND ${expenseSideSql('t', 'c')}`,
    '  AND t.pending = 0',
    `  AND t.date BETWEEN ${startDateLiteral} AND ${endDateLiteral}`,
  ].join('\n');
}

